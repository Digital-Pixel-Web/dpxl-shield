<?php
declare(strict_types=1);

namespace DPXL\Shield\Alerts;

use Dompdf\Dompdf;
use Dompdf\Options;

/**
 * Branded PDF rendering of the periodic security report.
 *
 * Draws the same figures as the activity email (via ReportData) but lays them
 * out for print in the Digital Pixel identity: charcoal header, orange accent,
 * A4 portrait. Rendered with Dompdf (pure PHP) so it runs on shared hosting
 * with no external binary.
 */
class PdfReport {

    // Digital Pixel brand palette.
    private const INK    = '#191919';
    private const ORANGE = '#F68B00';
    private const BLUE   = '#4F81BE';

    /**
     * Render the report to PDF bytes.
     *
     * @param  array<string,mixed> $data Shape from {@see ReportData::collect()}.
     * @return string Raw PDF document.
     */
    public function render(array $data): string {
        $options = new Options();
        $options->set('isRemoteEnabled', false);      // no outbound fetches from the HTML
        $options->set('isHtml5ParserEnabled', true);
        $options->set('defaultFont', 'DejaVu Sans');   // bundled, full Latin/pt-BR coverage
        $options->set('defaultPaperSize', 'a4');
        $options->set('tempDir', $this->tempDir());

        $dompdf = new Dompdf($options);
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->loadHtml($this->buildHtml($data), 'UTF-8');
        $dompdf->render();

        return (string) $dompdf->output();
    }

    /**
     * Generate the report and write it to a uniquely named file, returning the
     * path — used to attach the PDF to the activity email. Returns null if the
     * file could not be written (the email still goes out without it).
     *
     * @param array<string,mixed> $data
     */
    public function renderToFile(array $data): ?string {
        $path = trailingslashit($this->tempDir()) . $this->filename($data);

        return file_put_contents($path, $this->render($data)) !== false ? $path : null;
    }

    /** Human, dated download name, e.g. dpxl-shield-relatorio-2026-07-25.pdf. */
    public function filename(array $data): string {
        $host = sanitize_file_name(EmailTemplate::siteHost());
        $host = $host !== '' ? $host . '-' : '';

        return 'dpxl-shield-relatorio-' . $host . gmdate('Y-m-d') . '.pdf';
    }

    // ── HTML template ──────────────────────────────────────────────────────

    /** @param array<string,mixed> $data */
    public function buildHtml(array $data): string {
        $criticals = (int) ($data['criticalIssues'] ?? 0);
        $issues    = (int) ($data['scanIssues'] ?? 0);
        $level     = $criticals > 0 ? 'critical' : ($issues > 0 ? 'medium' : 'info');
        $accent    = $this->levelAccent($level);

        $period = $this->periodLabel((string) ($data['freq'] ?? 'weekly'));
        $since  = strtotime((string) ($data['since'] ?? '')) ?: time();
        $host   = esc_html(EmailTemplate::siteHost());

        $siteName = (string) get_option('blogname', '');
        $siteName = $siteName !== '' ? $siteName : EmailTemplate::siteHost();

        $range = sprintf(
            /* translators: 1: start date, 2: end date */
            esc_html__('Period from %1$s to %2$s', 'dpxl-shield'),
            esc_html(EmailTemplate::localTime($since, false)),
            esc_html(EmailTemplate::localTime(null, false))
        );

        $callout = $criticals > 0
            ? '<div class="callout"><strong>'
                . esc_html(sprintf(
                    /* translators: %d: number of critical issues */
                    _n(
                        '%d critical issue from the latest scan is still unresolved.',
                        '%d critical issues from the latest scan are still unresolved.',
                        $criticals,
                        'dpxl-shield'
                    ),
                    $criticals
                ))
                . '</strong></div>'
            : '';

        $generated = esc_html(EmailTemplate::localTime());

        return '<!DOCTYPE html><html><head><meta charset="UTF-8">'
            . '<style>' . $this->styles($accent) . '</style></head><body>'
            . '<div class="footer">'
                . esc_html__('Generated by DPXL Shield — Digital Pixel', 'dpxl-shield')
                . ' &middot; digitalpixel.com.br</div>'
            . '<div class="head">'
                . '<table class="head-t"><tr>'
                . '<td class="brand">DPXL <span>SHIELD</span></td>'
                . '<td class="brand-host">' . $host . '</td>'
                . '</tr></table>'
            . '</div>'
            . '<div class="rule"></div>'
            . '<div class="body">'
                . '<div class="pill">' . esc_html($period) . '</div>'
                . '<h1>' . esc_html(sprintf(
                    /* translators: %s: site name */
                    __('Security report — %s', 'dpxl-shield'),
                    $siteName
                )) . '</h1>'
                . '<p class="range">' . $range . '</p>'
                . $callout
                . $this->statGrid($data)
                . $this->topIpsTable((array) ($data['topIps'] ?? []))
                . '<p class="stamp">' . esc_html(sprintf(
                    /* translators: %s: date/time the report was generated */
                    __('Report generated on %s.', 'dpxl-shield'),
                    $generated
                )) . '</p>'
            . '</div>'
            . '</body></html>';
    }

    /** @param array<string,mixed> $data */
    private function statGrid(array $data): string {
        $blocked = number_format_i18n((int) ($data['attacksBlocked'] ?? 0));

        $secondary = [
            __('Logins', 'dpxl-shield')        => (int) ($data['loginSuccess'] ?? 0),
            __('Failed logins', 'dpxl-shield') => (int) ($data['loginFailed'] ?? 0),
            __('Scan issues', 'dpxl-shield')   => (int) ($data['scanIssues'] ?? 0),
        ];

        $cells = '';
        foreach ($secondary as $label => $value) {
            $cells .= '<td class="s-cell">'
                . '<div class="s-num">' . number_format_i18n($value) . '</div>'
                . '<div class="s-lab">' . esc_html((string) $label) . '</div>'
                . '</td>';
        }

        return '<table class="hero"><tr><td class="hero-cell">'
            . '<div class="hero-num">' . $blocked . '</div>'
            . '<div class="hero-lab">' . esc_html__('Attacks blocked', 'dpxl-shield') . '</div>'
            . '</td></tr></table>'
            . '<table class="stats"><tr>' . $cells . '</tr></table>';
    }

    /** @param array<int,array<string,mixed>> $topIps */
    private function topIpsTable(array $topIps): string {
        if ($topIps === []) {
            return '<p class="muted">' . esc_html__('No attacks were blocked in this period.', 'dpxl-shield') . '</p>';
        }

        $rows = '';
        foreach ($topIps as $row) {
            $rows .= '<tr>'
                . '<td>' . esc_html((string) ($row['ip'] ?? '')) . '</td>'
                . '<td class="r">' . number_format_i18n((int) ($row['hits'] ?? 0)) . '</td>'
                . '</tr>';
        }

        return '<h2>' . esc_html__('Most blocked IPs', 'dpxl-shield') . '</h2>'
            . '<table class="ips">'
            . '<tr class="th"><td>' . esc_html__('IP address', 'dpxl-shield') . '</td>'
            . '<td class="r">' . esc_html__('Blocks', 'dpxl-shield') . '</td></tr>'
            . $rows
            . '</table>';
    }

    private function styles(string $accent): string {
        $ink    = self::INK;
        $orange = self::ORANGE;

        return "
            @page { margin: 96px 48px 72px; }
            body { font-family: 'DejaVu Sans', sans-serif; color: #3c434a; font-size: 12px; }
            .head { position: fixed; top: -72px; left: 0; right: 0; height: 44px;
                    background: {$ink}; padding: 0 20px; }
            .head-t { width: 100%; height: 44px; }
            .brand { color: #fff; font-size: 14px; font-weight: bold; letter-spacing: 3px; vertical-align: middle; }
            .brand span { color: #8c9196; font-weight: normal; }
            .brand-host { color: #8c9196; font-size: 10px; text-align: right; vertical-align: middle; }
            .rule { position: fixed; top: -28px; left: 0; right: 0; height: 3px; background: {$orange}; }
            .footer { position: fixed; bottom: -48px; left: 0; right: 0; height: 30px;
                      color: #a7aaad; font-size: 9px; border-top: 1px solid #e2e4e7; padding-top: 8px; }
            h1 { color: {$ink}; font-size: 20px; font-weight: bold; margin: 14px 0 0; }
            h2 { color: #787c82; font-size: 11px; text-transform: uppercase; letter-spacing: 1px;
                 margin: 26px 0 8px; }
            .pill { display: inline-block; background: {$orange}; color: #fff; font-size: 10px;
                    font-weight: bold; text-transform: uppercase; letter-spacing: 1px;
                    padding: 3px 10px; border-radius: 10px; }
            .range { color: #787c82; font-size: 12px; margin: 8px 0 0; }
            .callout { margin: 18px 0 0; background: #fcf0f0; border-left: 3px solid {$accent};
                       padding: 11px 14px; color: {$ink}; font-size: 12px; }
            .hero { width: 100%; margin: 22px 0 0; border: 1px solid #e2e4e7; border-radius: 8px; }
            .hero-cell { padding: 18px; }
            .hero-num { color: {$ink}; font-size: 34px; font-weight: bold; }
            .hero-lab { color: #787c82; font-size: 12px; margin-top: 2px; }
            .stats { width: 100%; margin: 12px 0 0; border-collapse: separate; }
            .s-cell { width: 33%; padding: 14px; border: 1px solid #e2e4e7; }
            .s-num { color: {$ink}; font-size: 20px; font-weight: bold; }
            .s-lab { color: #787c82; font-size: 11px; margin-top: 2px; }
            .ips { width: 100%; margin: 4px 0 0; border: 1px solid #e2e4e7; border-collapse: collapse; }
            .ips td { padding: 9px 12px; border-top: 1px solid #eef0f1; color: {$ink}; }
            .ips .th td { background: #f6f7f7; color: #787c82; font-size: 10px;
                          text-transform: uppercase; letter-spacing: 1px; border-top: none; }
            .ips .r, .r { text-align: right; }
            .muted { color: #787c82; margin: 18px 0 0; }
            .stamp { color: #a7aaad; font-size: 10px; margin: 26px 0 0; }
        ";
    }

    // ── Helpers ────────────────────────────────────────────────────────────

    private function levelAccent(string $level): string {
        return match ($level) {
            'critical' => '#b32d2e',
            'medium'   => self::ORANGE,
            default    => self::BLUE,
        };
    }

    private function periodLabel(string $freq): string {
        return match ($freq) {
            'daily'   => __('Daily', 'dpxl-shield'),
            'monthly' => __('Monthly', 'dpxl-shield'),
            default   => __('Weekly', 'dpxl-shield'),
        };
    }

    /** Writable scratch dir — uploads when WordPress is loaded, system temp otherwise. */
    private function tempDir(): string {
        if (function_exists('get_temp_dir')) {
            return get_temp_dir();
        }

        return sys_get_temp_dir();
    }
}
