    ];

    /** @var array<string,array{0:string,1:string}> English singular → [pt singular, pt plural]. */
    private const PLURALS = [
        '%d critical issue from the latest scan is still unresolved.' => [
            '%d problema crítico da última varredura ainda não foi resolvido.',
            '%d problemas críticos da última varredura ainda não foram resolvidos.',
        ],
        '%d component is running an outdated version.' => [
            '%d componente está com versão desatualizada.',
            '%d componentes estão com versão desatualizada.',
        ],
    ];

    /**
     * Nesting depth. An alert sent from inside report generation would other-
     * wise deactivate the filters on its way out and leave the rest of the
     * report in English, so only the outermost deactivate() actually unhooks.
     */
    private static int $depth = 0;

    /** Installs the temporary translation filters for the duration of rendering. */
    public static function activate(): void {
        if (self::$depth++ > 0) {
            return;
        }

        add_filter('gettext', [self::class, 'filterGettext'], 20, 3);
        add_filter('ngettext', [self::class, 'filterNgettext'], 20, 5);
    }

    /** Removes the filters once the outermost caller is done. */
    public static function deactivate(): void {
        if (self::$depth > 0 && --self::$depth > 0) {
            return;
        }

        self::$depth = 0;

        remove_filter('gettext', [self::class, 'filterGettext'], 20);
        remove_filter('ngettext', [self::class, 'filterNgettext'], 20);
    }

    /**
     * @param  mixed $translated
     * @param  mixed $text
     * @param  mixed $domain
     */
    public static function filterGettext($translated, $text, $domain): string {
        if ($domain === 'dpxl-shield' && is_string($text) && isset(self::MAP[$text])) {
            return self::MAP[$text];
        }

        return is_string($translated) ? $translated : (string) $text;
    }

    /**
     * @param mixed $translated
     * @param mixed $single
     * @param mixed $plural
     * @param mixed $number
     * @param mixed $domain
     */
    public static function filterNgettext($translated, $single, $plural, $number, $domain): string {
        if ($domain === 'dpxl-shield' && is_string($single) && isset(self::PLURALS[$single])) {
            return (int) $number === 1 ? self::PLURALS[$single][0] : self::PLURALS[$single][1];
        }

        return is_string($translated) ? $translated : (string) $translated;
    }
}
